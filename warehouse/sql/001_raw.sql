-- Run separately, after approval, in an existing dedicated database.
-- DDL implicitly commits. Never execute this file inside a loading transaction.
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS OPS;
CREATE TABLE IF NOT EXISTS OPS.LOAD_MUTEX (
    LOCK_ID INTEGER NOT NULL, VERSION INTEGER NOT NULL
);
-- Bootstrap once with a single administrator session. Loaders require one row.
INSERT INTO OPS.LOAD_MUTEX (LOCK_ID, VERSION)
SELECT 1, 0 WHERE NOT EXISTS (SELECT 1 FROM OPS.LOAD_MUTEX WHERE LOCK_ID = 1);
CREATE TABLE IF NOT EXISTS RAW.SOURCE_OBJECT (
    OBJECT_ID VARCHAR NOT NULL, OBJECT_KEY VARCHAR NOT NULL, SHA256 VARCHAR(64) NOT NULL,
    PAYLOAD_TEXT VARCHAR(16777216) NOT NULL
);
CREATE TABLE IF NOT EXISTS RAW.BATCH_OBJECT (
    BATCH_ID VARCHAR(64) NOT NULL, REQUEST_INDEX INTEGER NOT NULL, OBJECT_ID VARCHAR(64) NOT NULL,
    ENDPOINT VARCHAR NOT NULL, PARAMS_TEXT VARCHAR NOT NULL, RETRIEVED_AT TIMESTAMP_TZ NOT NULL
);
CREATE TABLE IF NOT EXISTS RAW.INGESTION_RECORD (
    BATCH_ID VARCHAR(64) NOT NULL, DATASET VARCHAR NOT NULL, ROW_ORDINAL INTEGER NOT NULL,
    SOURCE VARCHAR NOT NULL, ENTITY VARCHAR NOT NULL, PAYLOAD_TEXT VARCHAR(16777216) NOT NULL,
    VALUE_TEXT VARCHAR, VALUE_NUMBER NUMBER(38,12)
);
CREATE TABLE IF NOT EXISTS RAW.SEC_SNAPSHOT_MEMBER LIKE RAW.INGESTION_RECORD;
CREATE TABLE IF NOT EXISTS RAW.NUMERIC_QUARANTINE (
    BATCH_ID VARCHAR(64) NOT NULL, RECORD_KIND VARCHAR NOT NULL, ROW_ORDINAL INTEGER NOT NULL,
    VALUE_TEXT VARCHAR NOT NULL, ERROR_CODE VARCHAR NOT NULL, PAYLOAD_TEXT VARCHAR(16777216) NOT NULL
);
CREATE TABLE IF NOT EXISTS OPS.BATCH_LOAD (
    BATCH_ID VARCHAR(64) NOT NULL, MANIFEST_HASH VARCHAR(64) NOT NULL, RECEIPT_HASH VARCHAR(64) NOT NULL,
    MANIFEST_TEXT VARCHAR(16777216) NOT NULL, RECEIPT_TEXT VARCHAR(16777216) NOT NULL,
    COUNTS_TEXT VARCHAR NOT NULL, COMMITTED_AT TIMESTAMP_TZ NOT NULL
);
