-- Run in the dedicated database with the owner role or approved auditor.
USE DATABASE FDEP_DEMO_DB;
USE WAREHOUSE FDEP_DEMO_WH;
SELECT CURRENT_ACCOUNT(), CURRENT_REGION(), CURRENT_ROLE(), CURRENT_WAREHOUSE();
SELECT LOCK_ID, VERSION FROM OPS.LOAD_MUTEX;
SELECT BATCH_ID, MANIFEST_HASH, RECEIPT_HASH, COUNTS_TEXT, COMMITTED_AT
FROM OPS.BATCH_LOAD ORDER BY COMMITTED_AT, BATCH_ID;
SELECT BATCH_ID, DATASET, COUNT(*) AS ROWS_LOADED
FROM RAW.INGESTION_RECORD GROUP BY BATCH_ID, DATASET ORDER BY BATCH_ID, DATASET;
SELECT BATCH_ID, DATASET, COUNT(*) AS SNAPSHOT_MEMBERS
FROM RAW.SEC_SNAPSHOT_MEMBER GROUP BY BATCH_ID, DATASET ORDER BY BATCH_ID, DATASET;
SELECT BATCH_ID, COUNT(*) AS REQUESTS FROM RAW.BATCH_OBJECT GROUP BY BATCH_ID ORDER BY BATCH_ID;
SELECT COUNT(*) AS UNIQUE_RAW_OBJECTS FROM RAW.SOURCE_OBJECT;
SELECT BATCH_ID, REQUEST_INDEX, COUNT(*) AS DUPLICATE_REQUESTS
FROM RAW.BATCH_OBJECT GROUP BY BATCH_ID, REQUEST_INDEX HAVING COUNT(*) <> 1;
SELECT OBJECT_ID, COUNT(*) AS DUPLICATE_OBJECTS
FROM RAW.SOURCE_OBJECT GROUP BY OBJECT_ID HAVING COUNT(*) <> 1;
SELECT B.BATCH_ID, B.REQUEST_INDEX
FROM RAW.BATCH_OBJECT B
LEFT JOIN RAW.SOURCE_OBJECT S ON B.OBJECT_ID = S.OBJECT_ID
LEFT JOIN OPS.BATCH_LOAD L ON B.BATCH_ID = L.BATCH_ID
WHERE S.OBJECT_ID IS NULL OR L.BATCH_ID IS NULL;
SELECT BATCH_ID, ERROR_CODE, COUNT(*) AS QUARANTINED
FROM RAW.NUMERIC_QUARANTINE GROUP BY BATCH_ID, ERROR_CODE;
SELECT OBJECT_ID, SHA256, SHA2(PAYLOAD_TEXT, 256) AS STORED_TEXT_SHA256
FROM RAW.SOURCE_OBJECT WHERE SHA256 <> SHA2(PAYLOAD_TEXT, 256);
SELECT BATCH_ID, COUNT(*) AS LEDGER_ENTRIES
FROM OPS.BATCH_LOAD GROUP BY BATCH_ID HAVING COUNT(*) <> 1;
SELECT BATCH_ID, DATASET, ROW_ORDINAL, COUNT(*) AS DUPLICATE_EVENTS
FROM RAW.INGESTION_RECORD GROUP BY BATCH_ID, DATASET, ROW_ORDINAL HAVING COUNT(*) <> 1;
SELECT BATCH_ID, DATASET, ROW_ORDINAL, COUNT(*) AS DUPLICATE_MEMBERS
FROM RAW.SEC_SNAPSHOT_MEMBER GROUP BY BATCH_ID, DATASET, ROW_ORDINAL HAVING COUNT(*) <> 1;
