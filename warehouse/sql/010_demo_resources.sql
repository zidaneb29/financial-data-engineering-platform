-- Provisioning artifact. Execute only after account, cost and resource approval.
-- Account: AWS Ohio Enterprise trial. STANDARD below is the warehouse type.
-- Fixed names are dedicated to this demonstration. Stop if any already exist.
USE ROLE SECURITYADMIN;
CREATE ROLE FDEP_DEMO_OWNER;
CREATE ROLE FDEP_DEMO_LOADER;
CREATE ROLE FDEP_DEMO_AUDITOR;
GRANT ROLE FDEP_DEMO_LOADER TO ROLE FDEP_DEMO_OWNER;
GRANT ROLE FDEP_DEMO_AUDITOR TO ROLE FDEP_DEMO_OWNER;
GRANT ROLE FDEP_DEMO_OWNER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE TRANSIENT DATABASE FDEP_DEMO_DB DATA_RETENTION_TIME_IN_DAYS = 0;
CREATE WAREHOUSE FDEP_DEMO_WH
    WAREHOUSE_TYPE = 'STANDARD'
    WAREHOUSE_SIZE = 'XSMALL'
    GENERATION = '1'
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    ENABLE_QUERY_ACCELERATION = FALSE
    STATEMENT_TIMEOUT_IN_SECONDS = 120
    STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 30;
USE ROLE SECURITYADMIN;
GRANT OWNERSHIP ON DATABASE FDEP_DEMO_DB TO ROLE FDEP_DEMO_OWNER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE FDEP_DEMO_WH TO ROLE FDEP_DEMO_OWNER COPY CURRENT GRANTS;

USE ROLE USERADMIN;
CREATE USER FDEP_DEMO_INGEST
    TYPE = SERVICE
    DISABLED = TRUE
    DEFAULT_ROLE = FDEP_DEMO_LOADER
    DEFAULT_SECONDARY_ROLES = ()
    DEFAULT_WAREHOUSE = FDEP_DEMO_WH;
USE ROLE SECURITYADMIN;
GRANT ROLE FDEP_DEMO_LOADER TO USER FDEP_DEMO_INGEST;

