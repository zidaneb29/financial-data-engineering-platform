DROP DATABASE IF EXISTS FDEP_DEMO_DB;
USE ROLE ACCOUNTADMIN;
DROP RESOURCE MONITOR IF EXISTS FDEP_DEMO_MONITOR;
USE ROLE SECURITYADMIN;
DROP USER IF EXISTS FDEP_DEMO_INGEST;
DROP ROLE IF EXISTS FDEP_DEMO_LOADER;
