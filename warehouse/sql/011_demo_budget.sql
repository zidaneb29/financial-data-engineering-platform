-- Execute only after approval. Resource monitoring is not a dollar hard cap.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR FDEP_DEMO_MONITOR
    WITH CREDIT_QUOTA = 1
    FREQUENCY = NEVER
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE FDEP_DEMO_WH SET RESOURCE_MONITOR = FDEP_DEMO_MONITOR;
